USE [CenterDB]
GO

DECLARE @ConstraintName SYSNAME
DECLARE @TableName SYSNAME
DECLARE @ColumnName SYSNAME

SET @TableName = 'Slot_FreeSpinRecord'
SET @ColumnName = 'IsCoupon'

SELECT 1 FROM INFORMATION_SCHEMA.CONSTRAINT_COLUMN_USAGE where TABLE_NAME = @TableName AND COLUMN_NAME = @ColumnName
IF EXISTS(SELECT 1 FROM INFORMATION_SCHEMA.CONSTRAINT_COLUMN_USAGE where TABLE_NAME = @TableName AND COLUMN_NAME = @ColumnName)
BEGIN
	SELECT @ConstraintName = CONSTRAINT_NAME FROM INFORMATION_SCHEMA.CONSTRAINT_COLUMN_USAGE where TABLE_NAME = @TableName AND COLUMN_NAME = @ColumnName
	EXEC('ALTER TABLE __TableName__ DROP CONSTRAINT ' + @ConstraintName)
END

ALTER TABLE [CenterDB].[Game].[Slot_FreeSpinRecord] DROP COLUMN [IsCoupon]