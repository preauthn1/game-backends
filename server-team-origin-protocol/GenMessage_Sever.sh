#############################################################
###! /bin/bash
### 
### 請先定義 $GOPATH/bin 路徑
### 
### 由於Project會把GOPATH設定成很多個資料夾，所以直接指定路徑比較好
### 
#############################################################

GOBIN=$1
OUTPUT=$2

#############################################################
### 開始執行
#############################################################

protoc --plugin=protoc-gen-go=${GOBIN}/protoc-gen-go  --go_out=${OUTPUT} ./*.proto 