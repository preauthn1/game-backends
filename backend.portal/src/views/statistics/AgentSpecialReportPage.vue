<template>
	<v-app v-if="renderComponent">
		<AgentSpecialReport />
	</v-app>
</template>

<script lang="ts">
import Vue from 'vue';
import { Component } from 'vue-property-decorator';
import EventBus from '@/utilities/event-bus';
import AgentSpecialReport from '@/components/statistics/merchant-summary/AgentSpecialReport.vue';

@Component({ components: { AgentSpecialReport } })
export default class AgentSpecialReportPage extends Vue {
	renderComponent: boolean = true;
	mounted() {
		this.registerReloadComponent();
	}
	registerReloadComponent() {
		EventBus.$on(`reload-${this.$router.currentRoute.path}`, (info: any) => {
			this.renderComponent = false;
			this.$nextTick(() => {
				this.renderComponent = true;
			});
		});
	}
}
</script>
